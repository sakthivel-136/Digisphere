function fmtTime(t: string | null) {
  if (!t) return '—'
  try { return new Date(t).toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit' }) }
  catch { return t }
}

function exportDashboardPDF(
  statsData: DashboardStats,
  factory: string,
  factoryName: string,
  date: string,
  adminName: string
) {
  const btn = document.getElementById('pdf-export-btn')
  if (btn) { btn.textContent = '⏳ Generating…'; btn.setAttribute('disabled', 'true') }

  try {
    const doc = new jsPDF()
    const w = doc.internal.pageSize.getWidth()
    const h = doc.internal.pageSize.getHeight()

    const drawBorder = () => {
      doc.setDrawColor(0, 0, 180)
      doc.setLineWidth(0.8)
      doc.rect(8, 8, w - 16, h - 16)
    }
    drawBorder()

    // ========== HEADER ==========
    doc.setFont('times', 'bold')
    doc.setTextColor(0, 0, 150)
    doc.setFontSize(20)
    doc.text('Security Patrol Analytics Report', w / 2, 22, { align: 'center' })
    doc.setFontSize(14)
    doc.text(factoryName.toUpperCase(), w / 2, 32, { align: 'center' })
    doc.setFont('times', 'bold')
    doc.setFontSize(12)
    doc.setTextColor(0, 0, 150)
    doc.text(`Date : ${date}`, 14, 44)
    doc.setFont('times', 'normal')
    doc.setFontSize(10)
    doc.setTextColor(40)
    doc.text(`Generated By : ${adminName}`, 14, 51)
    doc.text(`Generated At : ${new Date().toLocaleString()}`, 14, 57)

    let y = 68

    // ========== SUMMARY STATS & SHIFT BREAKDOWN ==========
    doc.setFont('times', 'bold')
    doc.setFontSize(13)
    doc.setTextColor(0, 0, 150)
    doc.text('Patrol Summary & Shift Accountability', 14, y)
    y += 6

    const dayShift = statsData.shifts?.day
    const nightShift = statsData.shifts?.night

    autoTable(doc, {
      startY: y,
      head: [['Metric', 'Overall Day', 'Day Shift (06:00 - 18:00)', 'Night Shift (18:00 - 06:00)']],
      body: [
        ['Effective Scans', String(statsData.total), String(dayShift?.total || 0), String(nightShift?.total || 0)],
        ['Completed Scans', `${statsData.completed} (${statsData.rate}%)`, `${dayShift?.completed || 0} (${dayShift?.rate || 0}%)`, `${nightShift?.completed || 0} (${nightShift?.rate || 0}%)`],
        ['Missed Scans', String(statsData.missed), String(dayShift?.missed || 0), String(nightShift?.missed || 0)],
        ['On-Duty Guards', '—', dayShift?.guards?.length ? dayShift.guards.join(', ') : 'None', nightShift?.guards?.length ? nightShift.guards.join(', ') : 'None'],
        ['Missed Rounds', '—', dayShift?.missedRounds?.length ? `Rounds: ${dayShift.missedRounds.join(', ')}` : 'None', nightShift?.missedRounds?.length ? `Rounds: ${nightShift.missedRounds.join(', ')}` : 'None'],
      ],
      theme: 'grid',
      styles: { font: 'times', fontSize: 9, cellPadding: 2.5 },
      headStyles: { fillColor: [0, 70, 160], textColor: 255, fontStyle: 'bold' },
      alternateRowStyles: { fillColor: [245, 248, 255] },
      columnStyles: { 0: { fontStyle: 'bold', cellWidth: 42 } },
      didParseCell: (data) => {
        if (data.section === 'body') {
          if (data.row.index === 1 && data.column.index > 0) data.cell.styles.textColor = [0, 130, 0]
          if (data.row.index === 2 && Number(data.cell.raw) > 0) data.cell.styles.textColor = [200, 0, 0]
        }
      },
      didDrawPage: () => drawBorder(),
    })
    y = (doc as any).lastAutoTable.finalY + 10

    // ========== SPEED ANOMALIES (INTEGRITY CHECK) ==========
    if (statsData.speedAnomalies && statsData.speedAnomalies.length > 0) {
      if (y > h - 45) { doc.addPage(); drawBorder(); y = 20 }
      doc.setFont('times', 'bold')
      doc.setFontSize(11)
      doc.setTextColor(200, 0, 0)
      doc.text(`[WARNING] ${statsData.speedAnomalies.length} Rapid Pacing / Potential Paper QR Scan Anomalies Detected`, 14, y)
      y += 5

      autoTable(doc, {
        startY: y,
        head: [['Round', 'Guard', 'Checkpoints', 'Elapsed Time', 'Pacing Rate', 'Flag']],
        body: statsData.speedAnomalies.map(a => [
          `Round ${a.round}`,
          a.guard,
          `${a.scansCount} checkpoints`,
          `${a.durationSec}s total`,
          `${a.avgSecPerScan}s/checkpoint`,
          'Speed Anomaly (Impossible Walking Pace)',
        ]),
        theme: 'grid',
        styles: { font: 'times', fontSize: 8, cellPadding: 2, halign: 'center' },
        headStyles: { fillColor: [180, 20, 20], textColor: 255, fontStyle: 'bold' },
        didDrawPage: () => drawBorder(),
      })
      y = (doc as any).lastAutoTable.finalY + 10
    }

    // ========== ROUND-BY-ROUND ==========
    if (statsData.roundSummary.length > 0) {
      if (y > h - 60) { doc.addPage(); drawBorder(); y = 20 }
      doc.setFont('times', 'bold')
      doc.setFontSize(13)
      doc.setTextColor(0, 0, 150)
      doc.text('Round-by-Round Breakdown', 14, y)
      y += 6

      autoTable(doc, {
        startY: y,
        head: [['Round', 'Completed', 'Missed', 'Total', 'Rate']],
        body: statsData.roundSummary.map(r => [
          r.round,
          String(r.completed),
          String(r.missed),
          String(r.completed + r.missed),
          `${r.completed + r.missed > 0 ? Math.round((r.completed / (r.completed + r.missed)) * 100) : 0}%`,
        ]),
        theme: 'grid',
        styles: { font: 'times', fontSize: 9, cellPadding: 2.5, halign: 'center' },
        headStyles: { fillColor: [0, 70, 160], textColor: 255, fontStyle: 'bold' },
        alternateRowStyles: { fillColor: [245, 248, 255] },
        didParseCell: (data) => {
          if (data.section === 'body') {
            if (data.column.index === 1) data.cell.styles.textColor = [0, 150, 0]
            if (data.column.index === 2 && Number(data.cell.raw) > 0) data.cell.styles.textColor = [200, 0, 0]
          }
        },
        didDrawPage: () => drawBorder(),
      })
      y = (doc as any).lastAutoTable.finalY + 12
    }

    // ========== SCAN POINT COVERAGE ==========
    if (statsData.coverageByPoint.length > 0) {
      if (y > h - 60) { doc.addPage(); drawBorder(); y = 20 }
      doc.setFont('times', 'bold')
      doc.setFontSize(13)
      doc.setTextColor(0, 0, 150)
      doc.text('Scan Point Coverage', 14, y)
      y += 6

      autoTable(doc, {
        startY: y,
        head: [['Scan Point', 'Completed', 'Missed', 'Coverage %']],
        body: statsData.coverageByPoint.map(p => {
          const pct = p.total ? Math.round((p.done / p.total) * 100) : 0
          return [p.name, String(p.done), String(p.total - p.done), `${pct}%`]
        }),
        theme: 'grid',
        styles: { font: 'times', fontSize: 9, cellPadding: 2.5 },
        headStyles: { fillColor: [0, 70, 160], textColor: 255, fontStyle: 'bold' },
        alternateRowStyles: { fillColor: [245, 248, 255] },
        columnStyles: { 1: { halign: 'center' }, 2: { halign: 'center' }, 3: { halign: 'center' } },
        didParseCell: (data) => {
          if (data.section === 'body' && data.column.index === 3) {
            const pct = parseInt(String(data.cell.raw))
            if (pct >= 80) data.cell.styles.textColor = [0, 150, 0]
            else if (pct >= 50) data.cell.styles.textColor = [200, 150, 0]
            else data.cell.styles.textColor = [200, 0, 0]
            data.cell.styles.fontStyle = 'bold'
          }
        },
        didDrawPage: () => drawBorder(),
      })
      y = (doc as any).lastAutoTable.finalY + 12
    }

    // ========== GUARD LEADERBOARD ==========
    if (statsData.guardLeaderboard.length > 0) {
      if (y > h - 60) { doc.addPage(); drawBorder(); y = 20 }
      doc.setFont('times', 'bold')
      doc.setFontSize(13)
      doc.setTextColor(0, 0, 150)
      doc.text('Guard Performance', 14, y)
      y += 6

      autoTable(doc, {
        startY: y,
        head: [['Rank', 'Guard Name', 'Scanned', 'Missed', 'Total', 'Rate']],
        body: statsData.guardLeaderboard.map((g, i) => [
          `#${i + 1}`,
          g.name,
          String(g.scanned),
          String(g.missed),
          String(g.total),
          `${g.total ? Math.round((g.scanned / g.total) * 100) : 0}%`,
        ]),
        theme: 'grid',
        styles: { font: 'times', fontSize: 9, cellPadding: 2.5 },
        headStyles: { fillColor: [0, 70, 160], textColor: 255, fontStyle: 'bold' },
        alternateRowStyles: { fillColor: [245, 248, 255] },
        columnStyles: { 0: { halign: 'center' }, 2: { halign: 'center' }, 3: { halign: 'center' }, 4: { halign: 'center' }, 5: { halign: 'center' } },
        didParseCell: (data) => {
          if (data.section === 'body' && data.column.index === 5) {
            const pct = parseInt(String(data.cell.raw))
            if (pct >= 90) data.cell.styles.textColor = [0, 150, 0]
            else if (pct >= 70) data.cell.styles.textColor = [200, 150, 0]
            else data.cell.styles.textColor = [200, 0, 0]
            data.cell.styles.fontStyle = 'bold'
          }
        },
        didDrawPage: () => drawBorder(),
      })
      y = (doc as any).lastAutoTable.finalY + 12
    }

    // ========== RECENT ACTIVITY ==========
    if (statsData.recentActivity.length > 0) {
      if (y > h - 60) { doc.addPage(); drawBorder(); y = 20 }
      doc.setFont('times', 'bold')
      doc.setFontSize(13)
      doc.setTextColor(0, 0, 150)
      doc.text('Recent Scan Activity (Last 10)', 14, y)
      y += 6

      autoTable(doc, {
        startY: y,
        head: [['Time', 'Guard', 'QR Point', 'Round', 'Status']],
        body: statsData.recentActivity.map(r => [
          r.scan_time ? new Date(r.scan_time).toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit' }) : '—',
          r.guard_name || '—',
          r.qr_name,
          `Round ${r.round}`,
          r.status,
        ]),
        theme: 'grid',
        styles: { font: 'times', fontSize: 9, cellPadding: 2.5 },
        headStyles: { fillColor: [0, 70, 160], textColor: 255, fontStyle: 'bold' },
        alternateRowStyles: { fillColor: [245, 248, 255] },
        didParseCell: (data) => {
          if (data.section === 'body' && data.column.index === 4) {
            if (data.cell.raw === 'SUCCESS') { data.cell.styles.textColor = [0, 150, 0]; data.cell.styles.fontStyle = 'bold' }
            if (data.cell.raw === 'MISSED') { data.cell.styles.textColor = [200, 0, 0]; data.cell.styles.fontStyle = 'bold' }
          }
        },
        didDrawPage: () => drawBorder(),
      })
    }

    // ========== FOOTER ON ALL PAGES ==========
    const pages = doc.getNumberOfPages()
    for (let i = 1; i <= pages; i++) {
      doc.setPage(i)
      doc.setFont('times', 'normal')
      doc.setFontSize(9)
      doc.setTextColor(120)
      doc.text(`Page ${i} of ${pages} | Security Verifier System`, w / 2, h - 12, { align: 'center' })
    }

    doc.save(`Analytics_Report_${factory}_${date}.pdf`)
  } catch (err) {
    console.error('PDF export error:', err)
    alert('Failed to generate PDF. Please try again.')
  } finally {
    if (btn) { btn.textContent = '📊 Export PDF'; btn.removeAttribute('disabled') }
  }
}

